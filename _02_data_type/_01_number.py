# 9223372036854775807 <class 'int'> -> 8byte 최대 크기 / 2의 64승
# 1 byte = 8bite
# 1 bit = 0 /1 한칸을 저장할 수 있는 크기

# 2진법, 8진법, 16진법 많이 씀
# 0b -> 2진법을 쓰겠다고 선언
a = 0b100
print(a, type(a))
# int로 타입이 적용되도 출력으로 나올때 10진수로 바뀜

# 0o -> 8진법을 쓰겠다고 선언

b = 0o23 # == 3과 8의 0승 + 3 , 2과 8의 1승을 더하면 19
print(b, type(b))

# 10진법 0~9 , 16진법 0~9, a, b, c, d, e, f

c = 0xff # 15와 16의 1승을 곱하면 255 / 255는 RGB값이라고 함
print(c, type(c))

