# 산술 연산(+, -, *(에스터리스크=별), /, //(몫), %(modulo, 나머지), **(거듭제곱))

print("---산술 연산---")
print(1 + 2) # 3
print(1 - 2) # -1
print(1 * 2) # 2
print(1 / 2) # 0.5 -> 몫을 구하지만 나누어 떨어질때까지의 몫을 구하는것
print(1 // 2) # 0 -> 정수 영역에서의 몫을 구하는것
print(1 % 2) # 1 -> 정수 영역에서의 나머지

# 거듭제곱
print(3 ** 2) # 9
print(3 ** 3) # 27
print(2 ** 63) # int 양의 최댓값 여기서 -를 곱하면 음의 최댓값

